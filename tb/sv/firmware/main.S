    .section .text
    .global _start

_start:
    li x1, 10           # x1 = 10 (0x0A)
    li x2, 20           # x2 = 20 (0x14)
    add x3, x1, x2      # x3 = 30 (0x1E)

    # --- بخش جدید برای نوشتن در حافظه ---
    li x4, 0x80001000   # آدرس هدف در حافظه را در x4 بارگذاری می‌کنیم
    sw x3, 0(x4)        # مقدار x3 (نتیجه جمع) را در آدرس داخل x4 می‌نویسیم

loop:
    j loop              # حلقه بی‌نهایت برای پایان برنامه

